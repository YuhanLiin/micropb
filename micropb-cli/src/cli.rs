use clap::{ArgAction, Parser, ValueEnum};
use std::ffi::OsString;
use std::path::PathBuf;

/// CLI interface for micropb-gen Protobuf compiler
#[derive(Parser, Debug, Clone)]
#[command(
    name = "micropb-cli",
    about = "Compile Protobuf files into Rust code using micropb-gen",
    version
)]
pub struct Cli {
    /// Protobuf files to compile
    #[arg(value_name = "PROTOS", required_unless_present = "fdset_in")]
    pub protos: Vec<PathBuf>,

    /// Path of the generated Rust output file
    #[arg(short = 'o', long = "output", value_name = "FILE", required = true)]
    pub output: PathBuf,

    /// Container types preset for repeated, map, string, and bytes fields
    #[arg(long = "container", value_enum, value_name = "CONTAINER")]
    pub container: Option<ContainerOpt>,

    /// Whether to include encode and decode logic
    #[arg(
        long = "encode-decode",
        value_enum,
        default_value_t = EncodeDecodeOpt::Both,
        value_name = "MODE",
        conflicts_with_all = ["encode_only", "decode_only"]
    )]
    pub encode_decode: EncodeDecodeOpt,

    /// Only include encode logic (shorthand for --encode-decode encode-only)
    #[arg(long = "encode-only", conflicts_with = "decode_only")]
    pub encode_only: bool,

    /// Only include decode logic (shorthand for --encode-decode decode-only)
    #[arg(long = "decode-only")]
    pub decode_only: bool,

    /// Do not calculate the MAX_SIZE constant on each message [default: true]
    #[arg(long = "no-calculate-max-size", action = ArgAction::SetFalse)]
    pub calculate_max_size: Option<bool>,

    /// Retain enum name prefixes in enum variant names [default: false]
    #[arg(long = "retain-enum-prefix", action = ArgAction::SetTrue)]
    pub retain_enum_prefix: Option<bool>,

    /// Do not format the generated Rust code [default: formatting enabled]
    #[arg(long = "no-format", action = ArgAction::SetFalse)]
    pub format: Option<bool>,

    /// Path where the file descriptor set generated by protoc will be written
    #[arg(
        long = "fdset-path",
        alias = "file-descriptor-set-path",
        value_name = "PATH"
    )]
    pub fdset_path: Option<PathBuf>,

    /// Compile a Protobuf file descriptor set file directly instead of compiling .proto files
    #[arg(
        long = "fdset-in",
        alias = "descriptor-set-in",
        value_name = "PATH",
        conflicts_with = "protos"
    )]
    pub fdset_in: Option<PathBuf>,

    /// Add an include directory for Protobuf imports (passed to protoc as -I<DIR>)
    #[arg(short = 'I', long = "include", value_name = "DIR", action = ArgAction::Append)]
    pub includes: Vec<PathBuf>,

    /// Additional argument to pass directly to the protoc invocation
    #[arg(long = "protoc-arg", value_name = "ARG", action = ArgAction::Append)]
    pub protoc_args: Vec<OsString>,

    /// Do not suffix package module names with an underscore [default: suffixing enabled]
    #[arg(long = "no-suffixed-package-names", action = ArgAction::SetFalse)]
    pub suffixed_package_names: Option<bool>,

    /// Generate an enum rather than a struct for messages with only a single oneof [default: false]
    #[arg(
        long = "single-oneof-msg-as-enum",
        default_missing_value = "true",
        num_args = 0..=1,
        action = ArgAction::Set
    )]
    pub single_oneof_msg_as_enum: Option<bool>,

    /// Do not generate doc comments from proto comments [default: enabled]
    #[arg(long = "no-comments-to-docs", action = ArgAction::SetFalse)]
    pub comments_to_docs: Option<bool>,

    /// Enable caching in generated encoding logic for length-delimited fields [default: false]
    #[arg(long = "encode-cache", action = ArgAction::SetTrue)]
    pub encode_cache: Option<bool>,

    /// Do not cache external types when encoding (requires encode_cache) [default: enabled]
    #[arg(long = "no-cache-extern-types", action = ArgAction::SetFalse)]
    pub cache_extern_types: Option<bool>,

    /// Map a Protobuf type path to an external Rust type (format: `.proto.Path=rust::Path`)
    #[arg(
        long = "extern-type-path",
        value_name = "PROTO_PATH=RUST_PATH",
        action = ArgAction::Append
    )]
    pub extern_type_paths: Vec<String>,

    /// Load a TOML configuration file, optionally scoped to a package (format: `FILE` or `FILE:PACKAGE`)
    #[arg(
        short = 'c',
        long = "config-file",
        alias = "config",
        value_name = "PATH[:PACKAGE]",
        action = ArgAction::Append
    )]
    pub config_files: Vec<String>,

    /// Automatically find and apply matching `.toml` configuration files next to each `.proto` file
    #[arg(long = "find-config-files", alias = "auto-config-files")]
    pub find_config_files: bool,

    /// Suppress warning messages
    #[arg(short = 'q', long = "quiet")]
    pub quiet: bool,
}

/// Container type choices for micropb-gen
#[derive(ValueEnum, Clone, Copy, Debug, PartialEq, Eq)]
pub enum ContainerOpt {
    /// heapless containers (heapless 0.9)
    Heapless,
    /// heapless containers for heapless 0.8
    #[value(name = "heapless-v0-8", alias = "heapless-0.8")]
    HeaplessV08,
    /// arrayvec containers
    Arrayvec,
    /// alloc containers (Vec, String, BTreeMap)
    Alloc,
    /// std containers (Vec, String, HashMap)
    Std,
}

/// Encode and decode generation options
#[derive(ValueEnum, Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum EncodeDecodeOpt {
    /// Generate both encode and decode logic
    #[default]
    Both,
    /// Generate encode logic only
    EncodeOnly,
    /// Generate decode logic only
    DecodeOnly,
}
